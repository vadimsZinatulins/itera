import { expect, test } from '@playwright/test';
import { admin, browserSignIn, provisionAccount } from './fixtures';

test('approval snapshots saved content, isolates revisions and explicitly replaces the Practice version', async ({ page }) => {
  const account = await provisionAccount();
  const headers = { origin: process.env.TEST_BASE_URL! };
  try {
    await browserSignIn(page, account.email);
    const subject = await (await page.request.post('/api/subjects', { headers, data: { name: 'Physics' } })).json();
    const input = { id: crypto.randomUUID(), subjectId: subject.id, revision: 0, title: 'Motion', description: 'Original description', blocks: [{ id: 'second', markdown: '## Velocity' }, { id: 'first', markdown: 'Distance over time.' }] };
    const saved = await (await page.request.post('/api/documents', { headers, data: input })).json();
    const approve = () => page.request.post('/api/documents/approve', { headers, data: { id: input.id, subjectId: subject.id, revision: saved.revision } });
    const approved = await approve();
    expect(approved.status()).toBe(200);
    const snapshot = { revision: 1, title: 'Motion', description: 'Original description', blocks: [{ id: 'second', markdown: '## Velocity' }, { id: 'first', markdown: 'Distance over time.' }] };
    expect((await approved.json()).practice_version).toEqual(snapshot);
    expect((await (await approve()).json()).practice_version).toEqual(snapshot);
    const revised = await (await page.request.post('/api/documents', { headers, data: { ...input, revision: 1, title: 'Revised motion', description: 'New description', blocks: [{ id: 'first', markdown: 'New Draft content' }] } })).json();
    expect(revised.practice_version).toEqual(snapshot);
    expect((await approve()).status()).toBe(409);
    const replaced = await page.request.post('/api/documents/approve', { headers, data: { id: input.id, subjectId: subject.id, revision: 2 } });
    expect(replaced.status()).toBe(200);
    const documents = await (await page.request.get(`/api/documents?subject=${subject.id}`)).json();
    expect(documents[0].practice_version).toEqual({ revision: 2, title: 'Revised motion', description: 'New description', blocks: [{ id: 'first', markdown: 'New Draft content' }] });
  } finally { await admin().auth.admin.deleteUser(account.id); }
});

test('learner reviews saved content before approval and can inspect the unchanged Practice version during Draft edits', async ({ page, browser }) => {
  const account = await provisionAccount();
  const headers = { origin: process.env.TEST_BASE_URL! };
  const other = await browser.newContext();
  try {
    await browserSignIn(page, account.email);
    const subject = await (await page.request.post('/api/subjects', { headers, data: { name: 'Writing' } })).json();
    await page.goto(`/?subject=${subject.id}`);
    await page.getByRole('button', { name: 'New Learning Document', exact: true }).click();
    await page.getByLabel('Document title', { exact: true }).fill('Saved title');
    await page.getByLabel('Document description', { exact: true }).fill('Saved description');
    await page.getByRole('button', { name: 'Add Markdown block', exact: true }).click();
    await page.getByLabel('Block 1 Markdown').fill('## Original\n\nMaterial encountered.');
    await expect(page.getByRole('button', { name: 'Ready to Practice', exact: true })).toBeDisabled();
    await page.getByRole('button', { name: 'Save block', exact: true }).click();
    await page.getByRole('button', { name: 'Save as Draft', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Saved on server');
    await page.getByRole('button', { name: 'Document preview', exact: true }).click();
    await page.keyboard.press('Escape');
    await expect(page.getByRole('button', { name: 'View practice version', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Ready to Practice', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await expect(dialog.getByRole('heading', { name: 'Saved title', exact: true })).toBeVisible();
    await expect(dialog.getByText('Saved description', { exact: true })).toBeVisible();
    await expect(dialog).toContainText('not demonstrated understanding');
    await dialog.getByRole('button', { name: 'Approve saved version', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    await expect(page.getByRole('status')).toContainText('Available for practice');
    await page.getByRole('article', { name: 'Block 1', exact: true }).hover();
    await page.getByRole('button', { name: 'Edit block 1', exact: true }).click();
    await page.getByLabel('Block 1 Markdown').fill('Unconfirmed local content');
    await expect(page.getByRole('button', { name: 'Update practice version', exact: true })).toBeDisabled();
    await page.getByRole('button', { name: 'View practice version', exact: true }).click();
    await expect(dialog.getByRole('heading', { name: 'Original', exact: true })).toBeVisible();
    await expect(dialog).not.toContainText('Unconfirmed local content');
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Discard local edits', exact: true }).click();
    await expect(page.getByLabel('Block 1 Markdown')).toHaveCount(0);
    await page.getByLabel('Document title', { exact: true }).fill('Revised title');
    await page.getByRole('article', { name: 'Block 1', exact: true }).hover();
    await page.getByRole('button', { name: 'Edit block 1', exact: true }).click();
    await page.getByLabel('Block 1 Markdown').fill('Replacement material');
    await page.getByRole('button', { name: 'Save block', exact: true }).click();
    await page.getByRole('button', { name: 'Save as Draft', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Draft revision');
    await page.getByRole('button', { name: 'All Learning Documents', exact: true }).click();
    await page.getByRole('button', { name: 'Drafts', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Open Revised title', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Draft revisions', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Open Revised title', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Available for practice', exact: true }).click();
    await page.getByLabel('Search Learning Documents').fill('Material encountered');
    await page.getByRole('button', { name: 'Open Revised title', exact: true }).click();
    await page.getByRole('button', { name: 'View practice version', exact: true }).click();
    await expect(dialog.getByRole('heading', { name: 'Saved title', exact: true })).toBeVisible();
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Update practice version', exact: true }).click();
    await expect(dialog).toContainText('Replacement material');
    await dialog.getByRole('button', { name: 'Approve saved version', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    const second = await other.newPage();
    await page.waitForTimeout(2100);
    await browserSignIn(second, account.email);
    await second.goto(`/?subject=${subject.id}`);
    await second.getByRole('button', { name: 'Open Revised title', exact: true }).click();
    await second.getByRole('button', { name: 'View practice version', exact: true }).click();
    await expect(second.getByRole('dialog')).toContainText('Replacement material');
    await page.reload();
    await page.getByRole('button', { name: 'Open Revised title', exact: true }).click();
    await page.getByRole('button', { name: 'View practice version', exact: true }).click();
    await expect(dialog).toContainText('Replacement material');
  } finally { await other.close(); await admin().auth.admin.deleteUser(account.id); }
});
